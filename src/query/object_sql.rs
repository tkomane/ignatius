//! Pure PostgreSQL quick-SQL builders for Object Tree selections.
//!
//! All builders format safe, quoted SQL templates for insertion into the active
//! SQL editor as a single undoable edit without executing anything against the
//! database.

use crate::postgres::metadata::ObjectKind;
use crate::query::identifiers::{is_identifier_start, quote_identifier, unquoted_identifier_end};
use std::collections::HashSet;
use std::fmt;

/// Default row cap for quick table/view preview queries.
pub const DEFAULT_PREVIEW_LIMIT: usize = 100;

/// Maximum number of columns rendered in quick SQL templates.
pub const MAX_OBJECT_SQL_COLUMNS: usize = 200;

/// Maximum byte size permitted for any generated quick SQL template (1 MiB).
pub const MAX_OBJECT_SQL_BYTES: usize = 1024 * 1024;

/// Errors returned when a quick SQL template cannot be built safely.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ObjectSqlError {
    /// A schema, relation, or column name was empty.
    EmptyIdentifier {
        /// Human label of the missing identifier.
        what: &'static str,
    },
    /// An identifier contained a NUL (`\0`) byte.
    EmbeddedNul {
        /// Human label of the offending identifier.
        what: &'static str,
    },
    /// No loaded columns were available for a column-dependent template.
    NoColumns,
    /// More than [`MAX_OBJECT_SQL_COLUMNS`] columns were provided.
    TooManyColumns {
        /// Number of columns supplied.
        count: usize,
        /// Configured cap.
        max: usize,
    },
    /// Rendered SQL exceeded [`MAX_OBJECT_SQL_BYTES`].
    ExceedsByteCap {
        /// Generated byte length.
        bytes: usize,
        /// Configured cap.
        max: usize,
    },
    /// The selected object kind does not support this SQL template.
    UnsupportedObjectKind {
        /// Human label of the object kind.
        kind: &'static str,
    },
}

impl fmt::Display for ObjectSqlError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::EmptyIdentifier { what } => write!(f, "{what} name cannot be empty"),
            Self::EmbeddedNul { what } => write!(f, "{what} contains a NUL byte"),
            Self::NoColumns => write!(f, "no loaded columns are available for this object"),
            Self::TooManyColumns { count, max } => {
                write!(f, "{count} columns exceeds the {max}-column quick-SQL cap")
            }
            Self::ExceedsByteCap { bytes, max } => {
                write!(
                    f,
                    "generated SQL ({bytes} bytes) exceeds the {max}-byte cap"
                )
            }
            Self::UnsupportedObjectKind { kind } => {
                write!(f, "quick SQL template is not supported for {kind}")
            }
        }
    }
}

impl std::error::Error for ObjectSqlError {}

/// Returns `true` when `kind` is a queryable PostgreSQL relation.
#[must_use]
pub const fn is_queryable_relation(kind: ObjectKind) -> bool {
    matches!(
        kind,
        ObjectKind::Table
            | ObjectKind::View
            | ObjectKind::MaterializedView
            | ObjectKind::PartitionedTable
            | ObjectKind::ForeignTable
    )
}

/// Returns `true` when `kind` accepts `INSERT INTO` templates.
#[must_use]
pub const fn is_insertable_relation(kind: ObjectKind) -> bool {
    matches!(
        kind,
        ObjectKind::Table | ObjectKind::PartitionedTable | ObjectKind::ForeignTable
    )
}

fn validate_identifier(name: &str, what: &'static str) -> Result<(), ObjectSqlError> {
    if name.is_empty() {
        return Err(ObjectSqlError::EmptyIdentifier { what });
    }
    if name.contains('\0') {
        return Err(ObjectSqlError::EmbeddedNul { what });
    }
    Ok(())
}

fn validate_columns(columns: &[String], require_non_empty: bool) -> Result<(), ObjectSqlError> {
    if require_non_empty && columns.is_empty() {
        return Err(ObjectSqlError::NoColumns);
    }
    if columns.len() > MAX_OBJECT_SQL_COLUMNS {
        return Err(ObjectSqlError::TooManyColumns {
            count: columns.len(),
            max: MAX_OBJECT_SQL_COLUMNS,
        });
    }
    for col in columns {
        validate_identifier(col, "column")?;
    }
    Ok(())
}

fn check_byte_cap(sql: String) -> Result<String, ObjectSqlError> {
    if sql.len() > MAX_OBJECT_SQL_BYTES {
        return Err(ObjectSqlError::ExceedsByteCap {
            bytes: sql.len(),
            max: MAX_OBJECT_SQL_BYTES,
        });
    }
    Ok(sql)
}

fn qualified_table(schema: &str, name: &str) -> Result<String, ObjectSqlError> {
    validate_identifier(schema, "schema")?;
    validate_identifier(name, "object")?;
    Ok(format!(
        "{}.{}",
        quote_identifier(schema),
        quote_identifier(name)
    ))
}

/// Builds a quoted `SELECT ... FROM "schema"."name" LIMIT N;` preview template.
///
/// When `columns` is empty (e.g. an unexpanded relation), falls back to `*`.
pub fn build_select_preview_sql(
    schema: &str,
    name: &str,
    columns: &[String],
    limit: usize,
) -> Result<String, ObjectSqlError> {
    let target = qualified_table(schema, name)?;
    validate_columns(columns, false)?;
    let effective_limit = limit.max(1);
    let projection = if columns.is_empty() {
        "*".to_owned()
    } else {
        columns
            .iter()
            .map(|c| quote_identifier(c))
            .collect::<Vec<_>>()
            .join(", ")
    };
    check_byte_cap(format!(
        "SELECT {projection}\nFROM {target}\nLIMIT {effective_limit};"
    ))
}

/// Builds `SELECT count(*) AS row_count FROM "schema"."name";`.
pub fn build_count_sql(schema: &str, name: &str) -> Result<String, ObjectSqlError> {
    let target = qualified_table(schema, name)?;
    check_byte_cap(format!("SELECT count(*) AS row_count\nFROM {target};"))
}

/// Builds an `INSERT INTO "schema"."name" (...) VALUES (:...);` template using
/// safe quoted column names and unique named parameter placeholders.
pub fn build_insert_template_sql(
    schema: &str,
    name: &str,
    columns: &[String],
) -> Result<String, ObjectSqlError> {
    let target = qualified_table(schema, name)?;
    validate_columns(columns, true)?;

    let quoted_cols: Vec<String> = columns.iter().map(|c| quote_identifier(c)).collect();
    let mut used_placeholders = HashSet::with_capacity(columns.len());
    let mut placeholders = Vec::with_capacity(columns.len());
    for (idx, col) in columns.iter().enumerate() {
        let base = sanitize_placeholder(col, idx + 1);
        let mut candidate = base.clone();
        let mut suffix = 2usize;
        while !used_placeholders.insert(candidate.clone()) {
            candidate = format!("{base}_{suffix}");
            suffix += 1;
        }
        placeholders.push(format!(":{candidate}"));
    }

    check_byte_cap(format!(
        "INSERT INTO {target} ({})\nVALUES ({});",
        quoted_cols.join(", "),
        placeholders.join(", "),
    ))
}

/// Builds a comma-separated list of quoted column identifiers.
pub fn build_column_list_sql(columns: &[String]) -> Result<String, ObjectSqlError> {
    validate_columns(columns, true)?;
    let list = columns
        .iter()
        .map(|c| quote_identifier(c))
        .collect::<Vec<_>>()
        .join(", ");
    check_byte_cap(list)
}

fn sanitize_placeholder(column: &str, one_based_index: usize) -> String {
    let mut out = String::new();
    for ch in column.chars() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    let trimmed = out.trim_matches('_').to_owned();
    let base = if trimmed.is_empty() {
        format!("param_{one_based_index}")
    } else if trimmed
        .chars()
        .next()
        .is_some_and(|first| first == '_' || first.is_ascii_alphabetic())
    {
        trimmed
    } else {
        format!("p_{trimmed}")
    };

    // Confirm the identifier satisfies ignatius named-parameter parsing.
    let bytes = base.as_bytes();
    let valid = bytes.first().copied().is_some_and(is_identifier_start)
        && unquoted_identifier_end(bytes, 0) == bytes.len();
    if valid {
        base
    } else {
        format!("param_{one_based_index}")
    }
}

