fn pct_change(baseline: f64, delta: f64) -> Option<f64> {
    if !baseline.is_finite() || !delta.is_finite() || baseline.abs() <= COST_EPSILON {
        None
    } else {
        Some((delta / baseline) * 100.0)
    }
}

fn signed_delta(baseline: u64, candidate: u64) -> i64 {
    let a = i64::try_from(baseline).unwrap_or(i64::MAX);
    let b = i64::try_from(candidate).unwrap_or(i64::MAX);
    b.saturating_sub(a)
}

fn write_metric_row(out: &mut String, metric: &str, a: &str, b: &str, delta: &str) {
    let _ = writeln!(
        out,
        "{:<22}  {:>16}  {:>16}  {:>20}",
        truncate_ascii(metric, 22),
        truncate_ascii(a, 16),
        truncate_ascii(b, 16),
        truncate_ascii(delta, 20),
    );
}

