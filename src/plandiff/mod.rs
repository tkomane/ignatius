//! Pure extended `EXPLAIN (BUFFERS, WAL, SETTINGS, FORMAT JSON)` parser and
//! A/B plan diff engine for Feature `054-explain-buffers-wal-and-plan-diff`.
//!
//! This module contains zero network, filesystem, process, or terminal I/O.
//! [`parse_extended_explain_json`] parses PostgreSQL 14-18 JSON EXPLAIN
//! payloads within [`MAX_PLAN_JSON_BYTES`] and [`MAX_PLAN_NODES`] bounds, and
//! [`diff_plans`] produces a deterministic [`PlanDiffReport`] with strictly
//! plain-ASCII table, plain-text, and JSON renderers.

